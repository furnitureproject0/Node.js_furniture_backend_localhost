import asyncHandler from 'express-async-handler';
import sequelize from '../config/database.js';
import { generateValidPassword } from '../services/helpers/index.js';
import { createUserService, updateUserService, getUsersService, deleteUserService } from '../services/user/index.js';
import { createNotification, sendNotification } from '../utils/notifications.js';
import sendEmail from '../utils/sendEmail.js'; 
import { sendNewClientAccountCredentialsTemplate } from '../utils/emailTemplates.js';
import AppError from '../utils/AppError.js';

export const getAllUsersByAdmin = asyncHandler(async (req, res) => {
    // Initialize transaction for read isolation
    const transaction = await sequelize.transaction();

    try {
        const { search, page, limit, role, is_verified, company_id } = req.query;

        const filters = {};
        if (role) filters.role = role;
        if (is_verified !== undefined) filters.is_verified = is_verified === 'true';
        if (company_id) filters.company_id = company_id;

        const result = await getUsersService(
            filters, 
            search, 
            { page, limit }, 
            { transaction }
        );

        await transaction.commit();

        res.status(200).json({
            success: true,
            message: 'Users retrieved successfully',
            data: result.users,
            meta: result.pagination
        });

    } catch (error) {
        if (transaction && !transaction.finished) {
            await transaction.rollback();
        }
        throw new AppError(error.message || 'Failed to retrieve users', 500);
    }
});


