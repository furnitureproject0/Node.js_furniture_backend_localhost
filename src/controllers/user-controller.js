export const createClientByAdmin = asyncHandler(async (req, res) => {
    const transaction = await sequelize.transaction();

    const autoGeneratedPassword = generateValidPassword(12);

    try {

        const body = req.body || {};
        const role = body.role || 'client';

        const userData = {
        ...body,
        password: body.password || autoGeneratedPassword,
        role,
        is_verified: role === 'client' ? false : true,
        creatorId: req.user.id
        };

        const { newUser } = await createUserService(userData, { transaction });

        const notification = await createNotification({
            title: 'Welcome to Angebots',
            message: `Hi ${newUser.name}, thank you for joining Angebots! Please verify your email to get started.`,
            type: 'welcome',
            actor_id: req.user.id,
            recipients: [newUser.id]
        }, { transaction });

        await transaction.commit();

        if (notification) {
            await sendNotification(notification);
        }

        await sendEmail({
            to: newUser.email,
            subject: 'Welcome to Angebots - Your Account Credentials',
            html: sendNewClientAccountCredentialsTemplate({
                name: newUser.name,
                email: newUser.email,
                password: userData.password 
            })
        });

        res.status(201).json({
            success: true,
            message: "Client created successfully. Credentials have been sent to their email.",
            data: {
                user: newUser.toJSON()
            }
        });

    } catch (error) {
        if (transaction && !transaction.finished) {
            await transaction.rollback();
        }
        throw error;
    }
});

export const updateClientByAdmin = asyncHandler(async (req, res) => {
    const transaction = await sequelize.transaction();

    try {
        const { id } = req.params; 
        const body = req.body || {};

        if (body.role) {
            delete body.role; 
        }

        const { updatedUser } = await updateUserService(id, body, { transaction });

        const notification = await createNotification({
            title: 'Your Profile Has Been Updated',
            message: `Hi ${updatedUser.name}, your profile information has been updated by an admin. Please review the changes.`,
            type: 'account',
            actor_id: req.user.id,
            recipients: [updatedUser.id]
        }, { transaction });

        await transaction.commit();

        if (notification) {
            await sendNotification(notification);
        }

        res.status(200).json({
            success: true,
            message: "Client updated successfully",
            data: {
                user: updatedUser.toJSON()
            }
        });

    } catch (error) {
        if (transaction && !transaction.finished) {
            await transaction.rollback();
        }
        throw error;
    }
});

export const deleteUserByAdmin = asyncHandler(async (req, res) => {
    const transaction = await sequelize.transaction();

    try {
        const { id } = req.params;

        await deleteUserService(id, { transaction });

        await transaction.commit();

        res.status(200).json({
            success: true,
            message: "User and associated data deleted successfully"
        });

    } catch (error) {
        if (transaction && !transaction.finished) {
            await transaction.rollback();
        }

        if (error.name === 'SequelizeForeignKeyConstraintError') {
            throw new AppError('Cannot delete user because they are linked to other records (e.g., orders, companies).', 400);
        }

        throw new AppError(error.message || 'Failed to delete user', error.statusCode || 500);
    }
});